func TestOracleProgramMetadataFixture(t *testing.T) {
	s := oracleFixture(t)
	fixtureRecords(t, s)
	ctx := context.Background()
	l, err := s.ReserveQuery(12)
	if err != nil {
		t.Fatal(err)
	}
	defer l.Release()
	statements := []string{
		`CREATE OR REPLACE VIEW "record_view" AS SELECT "id","note" FROM "records"`,
		`CREATE OR REPLACE PROCEDURE fixture_proc AS BEGIN NULL; END;`,
		`CREATE OR REPLACE FUNCTION fixture_fn RETURN NUMBER AS BEGIN RETURN 1; END;`,
		`CREATE OR REPLACE PACKAGE fixture_package AS PROCEDURE p; END fixture_package;`,
		`CREATE OR REPLACE PACKAGE BODY fixture_package AS PROCEDURE p AS BEGIN NULL; END; END fixture_package;`,
		`CREATE OR REPLACE TRIGGER fixture_trigger BEFORE UPDATE ON "records" FOR EACH ROW BEGIN NULL; END;`,
		`BEGIN EXECUTE IMMEDIATE 'DROP SEQUENCE fixture_seq'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -2289 THEN RAISE; END IF; END;`,
		`CREATE SEQUENCE fixture_seq START WITH 1 INCREMENT BY 2`,
		`CREATE OR REPLACE TYPE fixture_type AS OBJECT (value NUMBER);`,
	}
	for _, q := range statements {
		if _, err = l.Execute(ctx, "NYADB_IT", q); err != nil {
			t.Fatal("program fixture SQL", q, err)
		}
	}
	objects, err := s.Browse(ctx, s.Namespace("NYADB_IT"))
	if err != nil {
		t.Fatal(err)
	}
	found := map[string]bool{}
	for _, o := range objects {
		found[o.Ref.Kind] = true
		if o.Ref.Kind == "package" && (!strings.Contains(o.Definition, "PACKAGE BODY") || !strings.Contains(o.Definition, "PROCEDURE p")) {
			t.Fatal("package body missing", o.Definition)
		}
		if o.Ref.Kind == "sequence" && o.Name == "FIXTURE_SEQ" && !strings.Contains(o.Definition, "CREATE SEQUENCE") {
			t.Fatal("sequence definition missing")
		}
	}
	for _, kind := range []string{"table", "view", "procedure", "function", "package", "trigger", "sequence", "type"} {
		if !found[kind] {
			t.Fatal("missing metadata category", kind)
		}
	}
	view := s.Namespace("NYADB_IT").Object("view", "record_view")
	metadata, err := s.TableMetadata(ctx, view)
	if err != nil || metadata.Editable {
		t.Fatal("view editing boundary", metadata, err)
	}
}

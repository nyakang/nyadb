func TestOracleSharedDataFixture(t *testing.T) {
	s := oracleFixture(t)
	fixtureRecords(t, s)
	ctx := context.Background()
	id := s.ProfileID()
	schema := "NYADB_IT"
	ns, err := s.Namespaces(ctx)
	if err != nil || len(ns) == 0 || ns[0].Ref.Catalog != "XEPDB1" || ns[0].Ref.Schema != schema {
		t.Fatal(ns, err)
	}
	objects, err := s.Browse(ctx, s.Namespace(schema))
	if err != nil || len(objects) == 0 {
		t.Fatal(objects, err)
	}
	meta, err := s.tableMetadata(ctx, id, schema, "records")
	if err != nil || !meta.Editable || meta.Definition == "" {
		t.Fatal(meta, err)
	}
	page, err := s.page(ctx, id, schema, "records", contract.DataOptions{Limit: 10})
	if err != nil || len(page.Rows) != 1 || page.RowSnapshots[0] == nil {
		t.Fatal(page, err)
	}
	if c := page.Rows[0][2].Value; c.Kind != contract.Decimal || c.Text != "9007199254740993.1234567890123456789" {
		t.Fatal("NUMBER precision", c)
	}
	if !bytes.Equal(page.Rows[0][3].Value.Bytes, []byte{0, 255, 16}) || page.Rows[0][4].Value.Text != "2026-11-06T01:02:03.123456789" {
		t.Fatal("typed binary/timestamp", page.Rows[0])
	}
	saved, err := s.save(ctx, id, schema, "records", []contract.DataEdit{{Kind: "update", Original: page.RowSnapshots[0], Values: map[string]contract.DataValue{"note": {Text: "updated"}}}})
	if err != nil || !saved.CommitConfirmed || saved.Outcomes[0].Saved == nil {
		t.Fatal(saved, err)
	}
	if _, err = s.save(ctx, id, schema, "records", []contract.DataEdit{{Kind: "update", Original: page.RowSnapshots[0], Values: map[string]contract.DataValue{"note": {Text: "stale"}}}}); !errors.Is(err, contract.ErrDataConflict) {
		t.Fatal("stale snapshot accepted", err)
	}
	row, err := s.readRow(ctx, id, schema, "records", saved.Outcomes[0].Saved.Ref)
	if err != nil || row.Snapshot.Mode != "values" || row.Values["note"].Text != "updated" {
		t.Fatal(row, err)
	}
	var debugArgs []any
	debugWhere, debugErr := s.originalWhere(meta, row.Snapshot, &debugArgs)
	if debugErr != nil {
		t.Fatal("build values predicate", debugErr)
	}
	debugRows, debugErr := s.db.QueryContext(ctx, "SELECT ROWID FROM "+qualified(meta.Object)+" WHERE "+debugWhere, debugArgs...)
	if debugErr != nil {
		t.Fatal("values predicate fixture", debugErr)
	}
	debugRows.Close()
	saved, err = s.save(ctx, id, schema, "records", []contract.DataEdit{{Kind: "update", Original: row.Snapshot, Values: map[string]contract.DataValue{"note": {Text: "full snapshot"}}}})
	if err != nil || !saved.CommitConfirmed {
		t.Fatal("values snapshot", saved, err)
	}
	inserted, err := s.save(ctx, id, schema, "records", []contract.DataEdit{{Kind: "insert", Values: map[string]contract.DataValue{"note": {Text: "inserted"}, "amount": {Text: "0.00000000000000000001"}}}})
	if err != nil || inserted.Outcomes[0].Saved == nil {
		t.Fatal("identity/default insert", inserted, err)
	}
	chunk, err := s.chunk(ctx, id, schema, "records", "payload", saved.Outcomes[0].Saved.Ref, 1, 1)
	if err != nil || chunk.Text != "0xff" || !chunk.HasMore {
		t.Fatal(chunk, err)
	}
	tx, err := s.begin(ctx, id, schema, "records")
	if err != nil {
		t.Fatal(err)
	}
	_, err = s.DataTransactions().Save(ctx, tx, id, schema, "records", []contract.DataEdit{{Kind: "update", Original: saved.Outcomes[0].Saved, Values: map[string]contract.DataValue{"note": {Text: "rollback"}}}})
	if err != nil {
		t.Fatal(err)
	}
	if err = s.rollback(ctx, tx); err != nil {
		t.Fatal(err)
	}
	count, err := s.count(ctx, id, schema, "records")
	if err != nil || count != 2 {
		t.Fatal(count, err)
	}
	filtered, err := s.page(ctx, id, schema, "records", contract.DataOptions{Limit: 1, Filters: []contract.DataFilterRule{{Column: "note", Mode: "contains", Value: "snapshot"}}})
	if err != nil || len(filtered.Rows) != 1 {
		t.Fatal(filtered, err)
	}
	dateFiltered, err := s.page(ctx, id, schema, "records", contract.DataOptions{Limit: 10, Filters: []contract.DataFilterRule{{Column: "stamp", Mode: "greater", Value: "2026-11-05"}}})
	if err != nil || len(dateFiltered.Rows) != 1 {
		t.Fatal("typed timestamp filter", dateFiltered, err)
	}
	numericChunk, err := s.chunk(ctx, id, schema, "records", "amount", saved.Outcomes[0].Saved.Ref, 0, 1024)
	if err != nil || numericChunk.HasMore || numericChunk.Text != "9007199254740993.1234567890123456789" {
		t.Fatal("numeric field chunk", numericChunk, err)
	}
	var exported int
	err = s.export(ctx, id, schema, "records", contract.DataOptions{}, nil, func(v []contract.DataValue) error { exported++; return nil })
	if err != nil || exported != 2 {
		t.Fatal(exported, err)
	}
	analysis, err := s.analyze(ctx, id, schema, "records", contract.DataOptions{}, []string{"amount"})
	if err != nil || analysis.Rows != 2 || analysis.Columns[0].Numeric != 2 {
		t.Fatal(analysis, err)
	}
	imported, err := s.importRows(ctx, id, schema, "records", contract.DataImportRequest{Mode: "append", Edits: []contract.DataEdit{{Kind: "insert", Values: map[string]contract.DataValue{"note": {Text: "imported"}}}}})
	if err != nil || !imported.Committed {
		t.Fatal(imported, err)
	}
}
func TestOracleQueryAndCancellationFixture(t *testing.T) {
	s := oracleFixture(t)
	ctx := context.Background()
	l, err := s.ReserveQuery(8)
	if err != nil {
		t.Fatal(err)
	}
	defer l.Release()
	result, err := l.Execute(ctx, "NYADB_IT", `SELECT 9007199254740993.12345678901234567890 AS amount,q'[a;b]' AS note FROM dual; SELECT 2 FROM dual;`)
	if err != nil || len(result.Sets) != 2 || result.Sets[0].Rows[0][0].Text != "9007199254740993.1234567890123456789" {
		t.Fatal(result, err)
	}
	_, err = l.Execute(ctx, "NYADB_IT", `SELECT missing_column FROM dual`)
	if err == nil {
		t.Fatal("invalid SQL accepted")
	}
	if _, err = l.Execute(ctx, "NYADB_IT", `SELECT 1 FROM dual`); err != nil {
		t.Fatal("ordinary SQL error lost lease", err)
	}
	explain, err := queryplan.Build("oracle", `SELECT 1 FROM dual`)
	if err != nil {
		t.Fatal(err)
	}
	result, err = l.Execute(ctx, "NYADB_IT", explain)
	if err != nil {
		t.Fatal("EXPLAIN", err)
	}
	plan, err := queryplan.Parse("oracle", result)
	if err != nil || len(plan.Nodes) == 0 {
		t.Fatal(plan, err)
	}
	deadline, cancel := context.WithTimeout(ctx, 150*time.Millisecond)
	defer cancel()
	start := time.Now()
	_, err = l.Execute(deadline, "NYADB_IT", `BEGIN DBMS_SESSION.SLEEP(5); END;`)
	if !errors.Is(err, contract.ErrSQLSessionLost) || time.Since(start) > 2*time.Second {
		t.Fatal("cancel acknowledgement", err, time.Since(start))
	}
	if _, err = l.Execute(ctx, "NYADB_IT", `SELECT 1 FROM dual`); !errors.Is(err, contract.ErrSQLSessionLost) {
		t.Fatal("lost lease silently recovered", err)
	}
	replacement, err := l.Replace()
	if err != nil {
		t.Fatal(err)
	}
	defer replacement.Release()
	if _, err = replacement.Execute(ctx, "NYADB_IT", `SELECT 1 FROM dual`); err != nil {
		t.Fatal("explicit recovery", err)
	}
}
func TestOracleLOBFixture(t *testing.T) {
	s := oracleFixture(t)
	ctx := context.Background()
	l, _ := s.ReserveQuery(9)
	defer l.Release()
	_, _ = l.Execute(ctx, "NYADB_IT", `BEGIN EXECUTE IMMEDIATE 'DROP TABLE "lob_records" PURGE'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -942 THEN RAISE; END IF; END;`)
	for _, q := range []string{`CREATE TABLE "lob_records" ("id" NUMBER PRIMARY KEY,"text" CLOB,"blob" BLOB,"national" NCLOB)`, `INSERT INTO "lob_records" VALUES(1,TO_CLOB(RPAD('x',2000,'x')),TO_BLOB(HEXTORAW('00FF')),TO_NCLOB('中文'))`} {
		if _, err := l.Execute(ctx, "NYADB_IT", q); err != nil {
			t.Fatal(err)
		}
	}
	p, err := s.page(ctx, s.ProfileID(), "NYADB_IT", "lob_records", contract.DataOptions{Limit: 10})
	if err != nil || len(p.Rows) != 1 || !p.Rows[0][1].Truncated {
		t.Fatal(p, err)
	}
	chunk, err := s.chunk(ctx, s.ProfileID(), "NYADB_IT", "lob_records", "text", *p.RowRefs[0], 1024, 1024)
	if err != nil || len(chunk.Text) != 976 || chunk.HasMore {
		t.Fatal(chunk, err)
	}
	if s.crypto {
		if p.Editable == nil || !*p.Editable {
			t.Fatal("LOB privilege did not enable supported table edits")
		}
		saved, err := s.save(ctx, s.ProfileID(), "NYADB_IT", "lob_records", []contract.DataEdit{{Kind: "update", Original: p.RowSnapshots[0], Values: map[string]contract.DataValue{"text": {Text: "changed"}, "national": {Text: "中文更新"}, "blob": {Binary: true, Bytes: []byte{1, 2, 255}}}}})
		if err != nil || !saved.CommitConfirmed {
			t.Fatal("LOB fingerprints save", saved, err)
		}
		row, err := s.readRow(ctx, s.ProfileID(), "NYADB_IT", "lob_records", saved.Outcomes[0].Saved.Ref)
		if err != nil || row.Values["national"].Text != "中文更新" {
			t.Fatal("LOB full row", row, err)
		}
		saved, err = s.save(ctx, s.ProfileID(), "NYADB_IT", "lob_records", []contract.DataEdit{{Kind: "update", Original: row.Snapshot, Values: map[string]contract.DataValue{"text": {Text: "full LOB"}}}})
		if err != nil || !saved.CommitConfirmed {
			t.Fatal("LOB values save", saved, err)
		}
	}
	var rows int
	err = s.export(ctx, s.ProfileID(), "NYADB_IT", "lob_records", contract.DataOptions{}, nil, func(v []contract.DataValue) error {
		rows++
		if !strings.Contains(v[3].Text, "中文") {
			t.Fatal("NCLOB changed", v)
		}
		return nil
	})
	if err != nil || rows != 1 {
		t.Fatal("LOB export", rows, err)
	}
}


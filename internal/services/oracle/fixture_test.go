func oracleFixture(t *testing.T) *Session {
	t.Helper()
	if os.Getenv("NYADB_ORACLE_IT") != "1" {
		t.Skip("requires disposable Oracle fixture")
	}
	port, err := strconv.Atoi(os.Getenv("NYADB_ORACLE_PORT"))
	if err != nil || port < 1024 || port > 65535 {
		t.Fatal("explicit disposable loopback port required")
	}
	p, _ := connections.Defaults(connections.Oracle)
	p.ID = 71
	p.Name = "Oracle disposable fixture"
	p.Host = "127.0.0.1"
	p.Port = uint16(port)
	p.Username = "nyadb_it"
	p.OracleOptions.MaxConnections = 1
	v, err := OpenSession(context.Background(), p, os.Getenv("NYADB_ORACLE_PASSWORD"))
	if err != nil {
		t.Fatal(err)
	}
	s := v.(*Session)
	t.Cleanup(func() { s.Close() })
	return s
}

func TestPostgreSQLFieldsRoundTripCatalogGrammar(t *testing.T) {
	definitions := []string{
		`numeric(40,20) DEFAULT 12345678901234567890.12345678901234567890 NOT NULL`,
		`timestamp(6) with time zone[] DEFAULT ARRAY[NULL, now()]`,
		`"external"."default"[][] DEFAULT ARRAY[['first'::"external"."default"]]`,
		`text COLLATE "pg_catalog"."C" DEFAULT E'escaped\nquote\''::text NOT NULL`,
		`text DEFAULT $sql$semi;quote' NOT NULL$sql$::text NOT NULL`,
		`integer DEFAULT CASE WHEN true IS NOT NULL THEN CASE WHEN false THEN 3 ELSE 7 END ELSE 9 END NOT NULL`,
		`bigint GENERATED ALWAYS AS IDENTITY (SEQUENCE NAME "demo"."seq""name" INCREMENT BY -3 START WITH 9007199254740993 MINVALUE -9007199254740993 MAXVALUE 9007199254740999 CACHE 13 NO CYCLE) NOT NULL`,
		`bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL`,
		`bigint GENERATED ALWAYS AS ((id * 2)) STORED NOT NULL`,
		`text GENERATED ALWAYS AS (lower(value)) VIRTUAL`,
	}
	for _, raw := range definitions {
		f, err := ParsePostgreSQLField(raw)
		if err != nil || f.Unsupported {
			t.Fatalf("catalog field locked: %s: %+v %v", raw, f, err)
		}
		rendered, err := f.SQL()
		if err != nil {
			t.Fatal(raw, err)
		}
		parsed, err := ParsePostgreSQLField(rendered)
		if err != nil || pgFieldSignature(f) != pgFieldSignature(parsed) {
			t.Fatal("render changed field", raw, rendered, err)
		}
	}
	f, err := ParsePostgreSQLField(definitions[5])
	if err != nil || !strings.Contains(f.Default, "IS NOT NULL") || !strings.Contains(f.Default, "ELSE 9 END") || !f.NotNull {
		t.Fatal("CASE split into attributes", f, err)
	}
}

func TestPostgreSQLFieldUnknownAttributesCannotBecomeAlterType(t *testing.T) {
	for _, raw := range []string{`integer PRIMARY KEY`, `integer CHECK(value>0)`, `text REFERENCES other(value)`, `text CONSTRAINT unique_value UNIQUE`} {
		f, err := ParsePostgreSQLField(raw)
		if err != nil || !f.Unsupported || f.Extras == "" {
			t.Fatal("unknown column constraints were silently discarded", raw, f, err)
		}
		if _, err = f.SQL(); err == nil {
			t.Fatal("unknown attributes acquired write permission")
		}
	}
}

func TestPostgreSQLFieldRejectsMultiClauseAndEscapeInjection(t *testing.T) {
	for _, raw := range []string{
		`text; DROP TABLE other`, `text, injected integer`, `text DEFAULT (1))`, `text DEFAULT ARRAY[1,2)`,
		`text DEFAULT 'unterminated`, `text DEFAULT $open$never closed`, `text /* unterminated`,
		"text DEFAULT E'escape\\' ; DROP TABLE other", `text NOT NULL NOT NULL`,
		`bigint GENERATED ALWAYS AS IDENTITY DEFAULT 3`, `integer GENERATED BY DEFAULT AS (id) STORED`,
		`integer GENERATED ALWAYS AS (id)`, `[text]`, "`text`",
	} {
		if _, err := ParsePostgreSQLField(raw); err == nil {
			t.Fatalf("unsafe field accepted: %s", raw)
		}
	}
	for _, f := range []PostgreSQLField{
		{Type: `text DEFAULT 'unexpected'`},
		{Type: `text`, HasDefault: true, Default: `1 NOT NULL`},
		{Type: `text`, Collation: `"C" DEFAULT 'unexpected'`},
		{Type: `bigint`, Identity: "ALWAYS", IdentityOptions: `START WITH 1) , injected integer (`},
		{Type: `integer`, Generation: `id) STORED, injected integer GENERATED ALWAYS AS (id`, GenerationStorage: "STORED"},
	} {
		if _, err := f.SQL(); err == nil {
			t.Fatalf("form value changed its parsed meaning: %+v", f)
		}
	}
}
